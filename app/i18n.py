_current = DEFAULT_LANGUAGE


def normalize_language(code: str | None) -> str:
    """把任意 locale 文本归一化为受支持的语言代码，未知值回落到英文。"""
    if not code:
        return DEFAULT_LANGUAGE
    code = str(code).replace("-", "_")
    if code in _TRANSLATIONS:
        return code
    short = code.split("_")[0].lower()
    for candidate in _TRANSLATIONS:
        if candidate.split("_")[0].lower() == short:
            return candidate
    return DEFAULT_LANGUAGE


def detect_system_language() -> str:
    """读取系统语言；取不到时回落到英文。"""
    try:
        from PySide6.QtCore import QLocale

        return normalize_language(QLocale.system().name())
    except Exception:  # pragma: no cover - 非 Qt 环境下的兜底
        return DEFAULT_LANGUAGE


def set_language(code: str | None) -> str:
    global _current
    _current = normalize_language(code)
    return _current


def current_language() -> str:
    return _current


def language_name(code: str | None = None) -> str:
    return LANGUAGES.get(normalize_language(code or _current), LANGUAGES[DEFAULT_LANGUAGE])


def tr_raw(key: str) -> str:
    """返回未格式化的模板，供 pyqtgraph 自己处理 ``{value}`` 占位符。"""
    table = _TRANSLATIONS.get(_current, {})
    template = table.get(key)
    if template is None:
        template = _TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    return template


def tr(key: str, **kwargs) -> str:
    """取当前语言文案并填充占位符；缺参数时保留原占位符而不是抛异常。"""
    template = tr_raw(key)
    if not kwargs:
        return template
    try:
        return template.format_map(_SafeDict(kwargs))
    except (ValueError, IndexError):
        return template


class _SafeDict(dict):
    def __missing__(self, key: str) -> str:
        return "{" + key + "}"


